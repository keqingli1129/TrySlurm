#!/usr/bin/env bash
# Install Slurm on ONE machine that is both the controller (slurmctld) and the compute node (slurmd),
# with its NVIDIA GPU(s) registered as a GRES so jobs can request them with --gpus / --gres=gpu:1.
#
# Target: Ubuntu 22.04 / 24.04 or Debian 12 (apt-based). Run:  sudo ./setup-host-slurm.sh
# Safe to re-run: existing configs are backed up with a timestamp before being replaced.
set -euo pipefail

[[ $EUID -eq 0 ]] || { echo "Please run with sudo: sudo $0"; exit 1; }
command -v apt-get >/dev/null || { echo "This script expects an apt-based distro (Ubuntu/Debian)."; exit 1; }

echo "==> Checking the NVIDIA driver"
if ! nvidia-smi -L >/dev/null 2>&1; then
  cat <<'EOF'
nvidia-smi is not working. An RTX 50-series card needs driver 570 or newer, using the
"open" kernel modules. On Ubuntu:   sudo ubuntu-drivers install   (then reboot)
or pick a specific one, e.g.:       sudo apt install nvidia-driver-580-open
EOF
  exit 1
fi
NGPU=$(nvidia-smi -L | wc -l)
nvidia-smi --query-gpu=name,driver_version,memory.total --format=csv,noheader

echo "==> Installing munge, Slurm and python3-venv"
export DEBIAN_FRONTEND=noninteractive
apt-get update
apt-get install -y munge slurm-wlm python3-venv
id slurm >/dev/null 2>&1 || useradd --system --no-create-home --shell /usr/sbin/nologin slurm

echo "==> Setting up munge (Slurm's authentication)"
if [[ ! -s /etc/munge/munge.key ]]; then
  if command -v mungekey >/dev/null; then mungekey --create --force; else create-munge-key -f; fi
fi
chown munge:munge /etc/munge/munge.key
chmod 400 /etc/munge/munge.key
systemctl enable munge
systemctl restart munge
munge -n | unmunge | grep -q Success && echo "munge OK"

echo "==> Detecting hardware"
CONF_DIR=/etc/slurm
[[ -d /etc/slurm-llnl && ! -d /etc/slurm ]] && CONF_DIR=/etc/slurm-llnl   # very old Debian layout
mkdir -p "$CONF_DIR"
HOST=$(hostname -s)

HW=$(slurmd -C 2>/dev/null | head -n 1 || true)
if [[ "$HW" == NodeName=* ]]; then
  CPUS=$(grep -oP 'CPUs=\K[0-9]+' <<<"$HW")
  MEM=$(grep -oP 'RealMemory=\K[0-9]+' <<<"$HW")
  # keep CPUs/Boards/Sockets/Cores/Threads exactly as slurmd sees them
  HWLINE=$(sed -E 's/^NodeName=[^ ]+ //; s/ ?RealMemory=[0-9]+//' <<<"$HW")
else
  CPUS=$(nproc)
  MEM=$(free -m | awk '/^Mem:/{print $2}')
  HWLINE="CPUs=$CPUS"
fi
REALMEM=$(( MEM > 6144 ? MEM - 4096 : MEM * 3 / 4 ))   # leave room for the OS and desktop
DEFMEM=$(( REALMEM / CPUS ))
if (( NGPU == 1 )); then GPU_FILES=/dev/nvidia0; else GPU_FILES="/dev/nvidia[0-$((NGPU - 1))]"; fi
echo "host=$HOST  $HWLINE  RealMemory=${REALMEM}MB  GPUs=$NGPU ($GPU_FILES)"

echo "==> Writing $CONF_DIR/slurm.conf and gres.conf"
STAMP=$(date +%Y%m%d-%H%M%S)
for f in slurm.conf gres.conf; do
  [[ -f "$CONF_DIR/$f" ]] && cp "$CONF_DIR/$f" "$CONF_DIR/$f.bak-$STAMP"
done

cat >"$CONF_DIR/slurm.conf" <<EOF
# Generated by setup-host-slurm.sh on $(date)
ClusterName=homelab
SlurmctldHost=$HOST
SlurmUser=slurm
AuthType=auth/munge

StateSaveLocation=/var/spool/slurmctld
SlurmdSpoolDir=/var/spool/slurmd
SlurmctldPidFile=/run/slurmctld.pid
SlurmdPidFile=/run/slurmd.pid
SlurmctldLogFile=/var/log/slurm/slurmctld.log
SlurmdLogFile=/var/log/slurm/slurmd.log

# Keep process tracking simple (no cgroup setup needed). Fine for a single-user box.
ProctrackType=proctrack/linuxproc
MpiDefault=none
ReturnToService=2

SchedulerType=sched/backfill
SelectType=select/cons_tres
SelectTypeParameters=CR_Core_Memory
DefMemPerCPU=$DEFMEM

GresTypes=gpu
NodeName=$HOST $HWLINE RealMemory=$REALMEM Gres=gpu:$NGPU State=UNKNOWN
PartitionName=gpu Nodes=$HOST Default=YES MaxTime=INFINITE State=UP
EOF

cat >"$CONF_DIR/gres.conf" <<EOF
NodeName=$HOST Name=gpu File=$GPU_FILES
EOF

mkdir -p /var/spool/slurmctld /var/spool/slurmd /var/log/slurm
chown slurm:slurm /var/spool/slurmctld /var/log/slurm

echo "==> Starting slurmctld and slurmd"
systemctl enable slurmctld slurmd
systemctl restart slurmctld
sleep 2
systemctl restart slurmd
sleep 3
scontrol update NodeName="$HOST" State=RESUME >/dev/null 2>&1 || true

echo
sinfo -N -o "%N %P %T %c %m %G"
echo
echo "==> Test job: srun --gpus=1 nvidia-smi -L"
if timeout 60 srun --gpus=1 nvidia-smi -L; then
  echo
  echo "Slurm is up and can hand out the GPU."
  echo "Next, as your normal user (not sudo):  ./setup-python.sh"
else
  echo "Test job failed. Look at /var/log/slurm/slurmctld.log and /var/log/slurm/slurmd.log,"
  echo "and check: sinfo -R   (shows why a node is drained/down)"
  exit 1
fi
